namespace Strassio.Core.Placement
{
    /// <summary>Как укладывать шаг между стразами вдоль линии (docs/SPEC.md, раздел 4).</summary>
    public enum StepMode
    {
        /// <summary>Подгонка: шаг чуть меняется так, чтобы первая и последняя страза легли точно на края — без дырки в конце.</summary>
        FitEven,

        /// <summary>Точный шаг: фиксированное расстояние между центрами, остаток в конце может остаться пустым.</summary>
        ExactStep,

        /// <summary>Точное количество страз на всю кривую, распределяется по длине пропорционально.</summary>
        ExactCount,
    }
}
