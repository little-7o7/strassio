namespace Strassio.Core.Placement
{
    /// <summary>
    /// Как ряд страз проходит острый угол (docs/SPEC.md, разделы 4 и 6.1). Это не то же самое, что
    /// <see cref="CornerStyle"/>: тот отвечает за построение самой смещённой кривой (дуга или срез),
    /// а здесь — куда встают камни на уже готовой линии.
    ///
    /// На очень остром угле (кончик звезды, ~36°) страза в самой вершине плотной быть не может:
    /// две соседние с разных сторон упираются друг в друга и вынуждены разойтись — у вершины
    /// остаётся заметный просвет. Три круга в узкий клин плотно не ложатся. Плотно выходит только
    /// если убрать стразу из вершины и обойти кончик двумя стразами вплотную — то есть скруглить.
    /// Поэтому по умолчанию «смешанно»: тупые углы острые, очень острые скругляются сами.
    /// </summary>
    public enum CornerPlacement
    {
        /// <summary>Угол тупее порога — страза точно в вершине; острее порога — мягкое скругление.</summary>
        Mixed = 0,

        /// <summary>Всегда страза точно в вершине.</summary>
        Sharp = 1,

        /// <summary>Всегда скругление: вершина обходится двумя стразами вплотную, камня в самой вершине нет.</summary>
        Round = 2,
    }
}
